// Build step: validates the fund files and bundles all editorial data
// (funds, budget, settings, automatic figures) into one module that the
// Cloudflare Pages Function imports (functions/_lib/data.js). Run: node scripts/build.js
// Cloudflare runs it on every deploy (build command: npm run build).
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const OUT = path.join(ROOT, 'functions', '_lib', 'data.js');

const STATUSES = ['passed_on', 'completed', 'operational', 'ongoing', 'stalled', 'defects',
  'under_review', 'disbursed', 'not_disbursed', 'repaid', 'unclear', 'pending_data'];
const CLARITY = ['documented', 'reported', 'unclear', 'pending'];
const OBSERVED_STATUS = ['completed', 'operational', 'ongoing', 'stalled', 'defects', 'abandoned', 'not_started', 'unsure'];
const CONTACT_TYPES = ['correction', 'right_of_reply', 'takedown', 'new_evidence', 'suggest_fund', 'general'];

const readJson = f => JSON.parse(fs.readFileSync(f, 'utf8'));

function loadFunds() {
  const dir = path.join(DATA, 'funds');
  const funds = [];
  for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
    const fund = readJson(path.join(dir, file));
    const ids = new Set(fund.nodes.map(n => n.id));
    const problems = [];
    for (const n of fund.nodes) {
      if (!STATUSES.includes(n.status)) problems.push(`node ${n.id}: bad status "${n.status}"`);
      if (!CLARITY.includes(n.clarity)) problems.push(`node ${n.id}: bad clarity "${n.clarity}"`);
    }
    for (const l of fund.links) {
      if (!ids.has(l.from) || !ids.has(l.to)) problems.push(`link ${l.from}->${l.to}: unknown node`);
      if (!(l.amount > 0)) problems.push(`link ${l.from}->${l.to}: amount must be > 0`);
    }
    if (funds.some(f => f.id === fund.id)) problems.push(`duplicate fund id "${fund.id}"`);
    if (problems.length) throw new Error(`Invalid fund file ${file}:\n  ` + problems.join('\n  '));
    funds.push(fund);
  }
  return funds;
}

// How much of the money can be traced to a documented end point?
function clarityBreakdown(fund) {
  const outgoing = new Set(fund.links.map(l => l.from));
  const byId = new Map(fund.nodes.map(n => [n.id, n]));
  const totals = { documented: 0, reported: 0, unclear: 0, pending: 0 };
  for (const l of fund.links) {
    const target = byId.get(l.to);
    if (outgoing.has(target.id)) continue; // only count money reaching an end point
    totals[target.clarity] += l.amount;
  }
  const sum = Object.values(totals).reduce((a, b) => a + b, 0) || 1;
  const out = {};
  for (const k of Object.keys(totals)) out[k] = totals[k] / sum;
  return out;
}

function fundSummary(f) {
  return {
    id: f.id, order: f.order ?? 99, title: f.title, simple: f.simple, verdict: f.verdict || [], category: f.category, source: f.source, amount: f.amount,
    currency: f.currency, date: f.date, asOf: f.asOf, status: f.status, summary: f.summary,
    clarity: clarityBreakdown(f), endpoints: f.nodes.filter(n => !f.links.some(l => l.from === n.id)).length,
  };
}

// Automatic figures (written by scripts/update-live.js) override settings.json
const { SOURCES } = require('./update-live');
function liveSettings(base, live) {
  const s = { ...base };
  if (live.rate) Object.assign(s, {
    usdToNgn: live.rate.value, rateDate: live.rate.date, rateAuto: true,
    rateSource: { title: SOURCES.rate.title, url: SOURCES.rate.page },
  });
  if (live.population) Object.assign(s, {
    population: live.population.value, populationAuto: true,
    populationNote: `World Bank estimate for ${live.population.year}`,
    populationSource: { title: SOURCES.population.title, url: SOURCES.population.page },
  });
  return s;
}
function liveForFund(f, live) {
  const p = f.live && f.live.worldbankProject;
  return p && live.worldbank && live.worldbank[p] ? { worldbank: live.worldbank[p] } : null;
}

function build() {
  const funds = loadFunds();
  const settings = readJson(path.join(DATA, 'settings.json'));
  const budget = readJson(path.join(DATA, 'budget.json'));
  let live = { rate: null, population: null, worldbank: {}, errors: {}, lastRun: null };
  try { live = { ...live, ...readJson(path.join(DATA, 'live.json')) }; } catch (_) { /* no automatic data yet */ }

  const data = {
    builtAt: new Date().toISOString(),
    settings: liveSettings(settings, live),
    statuses: STATUSES, observedStatuses: OBSERVED_STATUS, contactTypes: CONTACT_TYPES,
    summaries: funds.map(fundSummary).sort((a, b) => a.order - b.order),
    funds: Object.fromEntries(funds.map(f => [f.id, { ...f, clarityBreakdown: clarityBreakdown(f), liveData: liveForFund(f, live) }])),
    budget, live,
  };
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, '// GENERATED by scripts/build.js. Do not edit; edit data/ instead.\nexport const DATA = ' + JSON.stringify(data) + ';\n');
  return data;
}

if (require.main === module) {
  const d = build();
  console.log(`Built ${path.relative(ROOT, OUT)}: ${Object.keys(d.funds).length} funds, budget years ${d.budget.years.map(y => y.year).join(', ')}`);
}

module.exports = { build, loadFunds, clarityBreakdown };
